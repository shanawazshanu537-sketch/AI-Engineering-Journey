a = 10
b = 3

# Arithmetic
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a // b)
print(a % b)
print(a ** b)

# Comparison
print(a > b)
print(a < b)
print(a == b)
print(a != b)

# Logical
x = True
y = False
print(x and y)
print(x or y)
print(not x)

